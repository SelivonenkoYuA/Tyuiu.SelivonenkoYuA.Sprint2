using System;
using tyuiu.cources.programming.interfaces.Sprint2;

namespace Tyuiu.SelivonenkoYuA.Sprint2.Task2.V11.Lib
{
    public class DataService : ISprint2Task2V11
    {
        public bool CheckDotInShadedArea(int x, int y)
        {
            // Точка должна быть внутри заштрихованной области.
            // Разбиваем фигуру на прямоугольники и объединяем через ||

            bool res = false;

            // 1. Верхний левый "зуб" (строки 3-4, столбцы 2-4)
            if ((y >= 3 && y <= 4) && (x >= 2 && x <= 4)) res = true;

            // 2. Верхний центральный выступ (строки 3-5, столбцы 6-8)
            if ((y >= 3 && y <= 5) && (x >= 6 && x <= 8)) res = true;

            // 3. Правее верхнего центра (строка 5, столбцы 11-12)
            if (y == 5 && (x >= 11 && x <= 12)) res = true;

            // 4. Левая длинная полоса (строки 6-7, столбцы 1-4)
            if ((y >= 6 && y <= 7) && (x >= 1 && x <= 4)) res = true;

            // 5. Основной блок (строки 6-11, столбцы 5-11)
            if ((y >= 6 && y <= 11) && (x >= 5 && x <= 11)) res = true;

            // 6. Строка 8, выступ вправо (столбец 12)
            if (y == 8 && x == 12) res = true;

            // 7. Строка 11 (продолжение основного блока влево, столбцы 4-5)
            if (y == 11 && (x >= 4 && x <= 5)) res = true;

            // 8. Строка 12 (нижний выступ, столбцы 4-5)
            if (y == 12 && (x >= 4 && x <= 5)) res = true;

            // 9. Строка 12 (нижний выступ, столбцы 8-10)
            if (y == 12 && (x >= 8 && x <= 10)) res = true;

            return res;
        }
    }
}